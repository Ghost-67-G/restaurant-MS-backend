const express = require('express');
const auth = require('../../middlewares/auth');
const validate = require('../../middlewares/validate');
const { PERMISSIONS } = require('../../config/permissions');
const userValidation = require('./validation');
const userController = require('./controller');

const router = express.Router();

router
  .route('/')
  .post(auth(PERMISSIONS.USER.MANAGE), validate(userValidation.createUser), userController.createUser)
  .get(auth(PERMISSIONS.USER.VIEW), validate(userValidation.getUsers), userController.getUsers);

router
  .route('/:userId')
  .get(auth(PERMISSIONS.USER.VIEW), validate(userValidation.getUser), userController.getUser)
  .patch(auth(PERMISSIONS.USER.MANAGE), validate(userValidation.updateUser), userController.updateUser)
  .delete(auth(PERMISSIONS.USER.MANAGE), validate(userValidation.deleteUser), userController.deleteUser);

module.exports = router;

